import assert from 'node:assert/strict'
import { chromium, type Page } from 'playwright-core'
import { preview } from 'vite'
const server=await preview({preview:{host:'127.0.0.1',port:0}})
const address=server.httpServer.address()
assert.ok(address && typeof address!=='string')
const browser=await chromium.launch({executablePath:process.env.CCL_CHROME_PATH,args:process.env.CCL_CHROME_PATH?['--ignore-gpu-blocklist','--enable-webgl','--use-angle=metal']:['--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const url=`http://127.0.0.1:${address.port}/?seed=4293693169`
const errors:string[]=[]
async function phase(page:Page,value:string){await page.waitForFunction(v=>document.querySelector('#game')?.getAttribute('data-phase')===v,value,{timeout:20000})}
try {
 const page=await browser.newPage({viewport:{width:1000,height:650},hasTouch:true})
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(url)
 await page.getByRole('button',{name:'Match setup',exact:true}).click()
 assert.equal(await page.locator('#setup-fielding').inputValue(),'auto')
 await page.locator('#setup-fielding').selectOption('manual')
 await page.locator('#setup-toss').selectOption('bowl')
 await page.getByRole('button',{name:/Start match/}).click()
 await phase(page,'ready')
 await page.reload()
 await page.getByRole('button',{name:'Match setup',exact:true}).click()
 assert.equal(await page.locator('#setup-fielding').inputValue(),'manual')
 await page.getByRole('button',{name:/Start match/}).click()
 await page.getByRole('button',{name:'Bowl',exact:true}).click()
 await phase(page,'field')
 await page.locator('#fielding-controls').waitFor()
 assert.equal(await page.locator('#bowl-controls').isVisible(),false)
 const status=await page.locator('#fielding-status').textContent()
 const selected=Number(status?.match(/Fielder (\d+)/)?.[1]??1)-1
 const player=page.locator(`#live-field-control [data-fielder="${selected}"]`)
 const before=await player.getAttribute('transform')
 const map=await page.locator('#live-field-control').boundingBox()
 assert.ok(map)
 await page.touchscreen.tap(map.x+map.width*.45,map.y+map.height*.45)
 await page.waitForFunction(({index,before})=>document.querySelector(`#live-field-control [data-fielder="${index}"]`)?.getAttribute('transform')!==before,{index:selected,before})
 await page.locator('#fielding-chase').tap()
 await page.waitForFunction(()=>document.querySelector('#fielding-controls')?.getAttribute('data-action')==='hold',undefined,{timeout:15000})
 await page.locator('#pause-button').click()
 const position=await player.getAttribute('transform')
 await page.keyboard.press('q')
 assert.equal(await player.getAttribute('transform'),position)
 await page.getByRole('button',{name:'Resume',exact:true}).click()
 for(const [width,height] of [[1000,650],[800,450],[390,844]]) {
  await page.setViewportSize({width,height})
  await page.evaluate(()=>new Promise(requestAnimationFrame))
  const bounds=await page.locator('#fielding-controls').boundingBox()
  const score=await page.locator('#scoreboard').boundingBox()
  assert.ok(bounds && score)
  assert.ok(bounds.y>=0 && bounds.x>=0 && bounds.x+bounds.width<=width)
  assert.ok(bounds.y+bounds.height<score.y)
  await page.screenshot({path:`/tmp/ccl-fielding-${width}.png`})
 }
 await page.locator('#throw-bowler').tap()
 await phase(page,'dead')
 const score=await page.locator('#score').textContent()
 const call=await page.locator('#call-title').textContent()
 await page.locator('#pause-button').click()
 await page.locator('#replay-button').click()
 await phase(page,'field')
 assert.ok(await page.locator('#fielding-chase').isDisabled())
 await phase(page,'dead')
 assert.equal(await page.locator('#score').textContent(),score)
 assert.equal(await page.locator('#call-title').textContent(),call)
 assert.deepEqual(errors,[])
 console.log(`Manual fielding browser passed: saved Solo setup, touch map movement, chase, live pickup/hold, pause lock, bowler-end throw, desktop/landscape/portrait layouts, score-preserving replay (${score}, ${call}). No page errors.`)
} finally {await browser.close();await server.close()}
