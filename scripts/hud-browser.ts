import assert from 'node:assert/strict'
import { chromium, type Page } from 'playwright-core'
import { preview } from 'vite'

const server = await preview({ preview: { host: '127.0.0.1', port: 0 } })
const address = server.httpServer.address()
assert.ok(address && typeof address !== 'string')
const browser = await chromium.launch({ executablePath: process.env.CCL_CHROME_PATH, args: process.env.CCL_CHROME_PATH ? ['--ignore-gpu-blocklist', '--enable-webgl', '--use-angle=metal'] : ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const errors: string[] = []
const url = `http://127.0.0.1:${address.port}/?seed=41`
const phase = (page: Page, value: string) => page.waitForFunction(value => document.querySelector('#game')?.getAttribute('data-phase') === value, value, { timeout: 20000 })
async function layout(page: Page, width: number, height: number) {
  await page.setViewportSize({ width, height })
  await page.evaluate(() => new Promise(requestAnimationFrame))
  const rects = await page.evaluate(() => {
    const box = (id: string) => { const b = document.getElementById(id)!.getBoundingClientRect(); return { x: b.x, y: b.y, right: b.right, bottom: b.bottom, width: b.width } }
    return { score: box('scoreboard'), loft: box('loft-toggle'), defense: box('defense-toggle'), next: box('next-button'), timing: box('timing'), pause: box('pause-button'), field: box('field-map-button') }
  })
  assert.equal(rects.score.x, 0)
  assert.equal(rects.score.right, width)
  assert.equal(rects.score.bottom, height)
  assert.ok(rects.loft.bottom < rects.score.y && rects.defense.bottom < rects.score.y)
  assert.ok(rects.loft.x > width / 2)
  assert.ok(rects.timing.right <= rects.pause.x)
  assert.ok(rects.field.right < rects.timing.x)
  assert.ok(rects.next.right <= rects.loft.x || rects.next.bottom < rects.loft.y, 'Next ball must not cover Loft')
  await page.screenshot({ path: `/tmp/ccl-hud-${width}.png` })
}
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } })
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'vibrate', { value: () => { document.documentElement.dataset.vibrated = 'true'; return true } })
  })
  await page.goto(url + '&play=training')
  await phase(page, 'windup')
  assert.equal(await page.locator('#shots-toggle, #shots, #shot-options').count(), 0)
  assert.equal(await page.locator('#sound-button').isVisible(), false)
  await page.locator('#loft-toggle').click()
  await page.waitForFunction(() => document.querySelector('#loft-toggle')?.getAttribute('aria-pressed') === 'true')
  await page.locator('#defense-toggle').click()
  await page.waitForFunction(() => document.querySelector('#loft-toggle')?.getAttribute('aria-pressed') === 'false')
  assert.equal(await page.locator('#defense-toggle').getAttribute('aria-pressed'), 'true')
  await page.locator('#defense-toggle').click()
  await page.locator('#pause-button').click()
  await page.locator('#auto-next').click()
  await page.locator('#match-settings').click()
  assert.equal(await page.locator('#settings-dialog').isVisible(), true)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('#settings-dialog').isVisible(), false)
  assert.equal(await page.locator('#overlay').isVisible(), true)
  await page.locator('#scorecard-button').click()
  assert.equal(await page.locator('#scorecard-dialog').isVisible(), true)
  await page.locator('#scorecard-close').click()
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  if (await page.locator('#game').getAttribute('data-phase') !== 'windup') {
    await phase(page, 'dead')
    await page.locator('#next-button').click()
  }
  await page.evaluate(() => new Promise<void>((resolve, reject) => {
    const start = performance.now()
    function check() {
      const percent = parseFloat(document.querySelector<HTMLElement>('#timing-needle')!.style.getPropertyValue('--timing'))
      if (document.querySelector('#game')?.getAttribute('data-phase') === 'flight' && percent >= 49 && percent <= 54) {
        document.dispatchEvent(new KeyboardEvent('keydown', { code: 'Space', key: ' ', bubbles: true }))
        resolve()
      } else if (performance.now() - start > 15000) reject(new Error('No timing window'))
      else requestAnimationFrame(check)
    }
    check()
  }))
  await phase(page, 'field')
  await page.screenshot({ path: '/tmp/ccl-bat-contact.png' })
  assert.match(await page.locator('#timing-result').textContent() ?? '', /PERFECT|GOOD/)
  if (await page.locator('#timing-result').textContent() === 'PERFECT') assert.equal(await page.locator('html').getAttribute('data-vibrated'), 'true')
  const before = await page.locator('#field-map [data-fielder]').evaluateAll(nodes => nodes.map(n => n.getAttribute('transform')))
  await page.waitForTimeout(350)
  const after = await page.locator('#field-map [data-fielder]').evaluateAll(nodes => nodes.map(n => n.getAttribute('transform')))
  assert.notDeepEqual(before, after, 'minimap must follow actual fielding movement')
  await phase(page, 'dead')
  assert.ok(await page.locator('#timing').isVisible(), 'timing verdict persists after the ball')
  assert.doesNotMatch(await page.locator('#callout').textContent() ?? '', /ms|perfect|good contact/i)
  for (const size of [[1280, 720], [800, 450], [390, 844]] as const) await layout(page, size[0], size[1])
  const score = await page.locator('#score').textContent()
  await page.locator('#pause-button').click()
  await page.locator('#replay-button').click()
  await phase(page, 'windup')
  await phase(page, 'dead')
  assert.equal(await page.locator('#score').textContent(), score)
  await page.locator('#next-button').click()
  await page.goto(url)
  await page.getByRole('button', { name: 'Match setup', exact: true }).click()
  await page.locator('#setup-toss').selectOption('bowl')
  await page.getByRole('button', { name: /Start match/ }).click()
  await phase(page, 'ready')
  await page.locator('#field-map-button').click()
  await page.locator('#field-select').selectOption('attack')
  const old = await page.locator('#field-editor [data-fielder="0"]').getAttribute('transform')
  await page.locator('#fielder-select').selectOption('0')
  const editor = await page.locator('#field-editor').boundingBox()
  assert.ok(editor)
  await page.mouse.click(editor.x + editor.width * .42, editor.y + editor.height * .49)
  await page.waitForFunction(old => document.querySelector('#field-editor [data-fielder="0"]')?.getAttribute('transform') !== old, old)
  const saved = await page.locator('#field-editor [data-fielder="0"]').getAttribute('transform')
  await page.mouse.click(editor.x + 2, editor.y + 2)
  assert.match(await page.locator('#field-notice').textContent() ?? '', /inside the boundary/)
  assert.equal(await page.locator('#field-editor [data-fielder="0"]').getAttribute('transform'), saved)
  await page.screenshot({ path: '/tmp/ccl-field-editor.png' })
  await page.locator('#field-close').click()
  await page.locator('#next-button').click()
  await phase(page, 'windup')
  assert.equal(await page.locator('#field-map [data-fielder="0"]').getAttribute('transform'), saved)
  await page.locator('#field-map-button').click()
  assert.equal(await page.locator('#field-select').isDisabled(), true, 'field cannot change after the delivery begins')
  await page.locator('#field-close').click()
  await phase(page, 'dead')
  assert.deepEqual(errors, [])
  console.log('HUD browser passed: desktop, landscape and portrait layout; exclusive batting modes; timing and haptics; live field movement; legal field editing; pause/settings/scorecard; score-preserving replay. No page errors.')
} finally { await browser.close(); await server.close() }
